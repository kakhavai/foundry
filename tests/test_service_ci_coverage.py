def test_workflow_trigger_covers_every_filter_path():
    """The silent-failure guard, and the reason this test exists at all.

    `services.yml` has a workflow-level `paths:` trigger so the gitops bot's
    image-tag commits do not start a run. That list must remain a SUPERSET of
    every path any per-service filter names — a path filtered by
    changed-services but not present here never reaches the filter, because
    the workflow never starts. The symptom is not a failure; it is that a
    service's CI stops running and nobody notices.
    """
    triggers = _workflow()["on"]
    rules, _ = filters.build(SERVICES)
    every_filtered_path = {path for paths in rules.values() for path in paths}

    for event in ("pull_request", "push"):
        declared = set(triggers[event]["paths"])
        for path in sorted(every_filtered_path):
            assert any(_covers(prefix, path) for prefix in declared), (
                f"{event}: the workflow-level paths trigger does not cover "
                f"{path!r}, so a change to it never starts the workflow and "
                f"the filter that names it can never match"
            )


def _covers(declared: str, path: str) -> bool:
    """Whether a trigger glob subsumes a filter glob.

    Only the two shapes actually used: an exact match, or a `dir/**` prefix
    that contains the filtered path.
    """
    if declared == path:
        return True
    if declared.endswith("/**"):
        return path.startswith(declared[: -len("**")])
    return False


# ── the ApplicationSet reproduces what the hand-written manifests did ────────


def test_generated_application_keeps_the_gitops_guarantees():
    """CLAUDE.md's "ArgoCD / GitOps Behavior" rests on all three of these.

    Losing selfHeal or prune would not fail a sync — it would quietly stop
    reverting manual cluster edits, which is the behaviour the whole GitOps
    section describes.
    """
    template = _yaml(APPLICATIONSET)["spec"]["template"]
    automated = template["spec"]["syncPolicy"]["automated"]
    assert automated["prune"] is True
    assert automated["selfHeal"] is True
    assert template["spec"]["source"]["targetRevision"] == "main"


def test_generated_application_matches_the_manifests_it_replaced():
    """The specs are byte-identical modulo the name — pinned so a later edit
    to the template cannot silently change what is deployed.

    These literals are the previous contents of
    infra/gitops/argo/<service>.yaml, which no longer exist to diff against.
    """
    template = _yaml(APPLICATIONSET)["spec"]["template"]
    name = "{{.path.basename}}"

    assert template["metadata"]["name"] == name
    assert template["metadata"]["namespace"] == "argocd"
    assert template["metadata"]["finalizers"] == ["resources-finalizer.argocd.io"]

    spec = template["spec"]
    assert spec["project"] == "default"
    assert spec["source"] == {
        "repoURL": "https://github.com/kakhavai/foundry",
        "targetRevision": "main",
        "path": "helm/charts/generic-service",
        "helm": {
            "valueFiles": [
                f"/helm/values/{name}/values.yaml",
                f"/infra/gitops/envs/local/{name}/values.yaml",
            ]
        },
    }
    assert spec["destination"] == {
        "server": "https://kubernetes.default.svc",
        "namespace": "default",
    }
    assert spec["syncPolicy"]["syncOptions"] == ["CreateNamespace=true"]


def test_applicationset_uses_gotemplate_with_strict_missing_keys():
    """`missingkey=error` is why a typo'd field fails the generator instead of
    producing an Application named "" or a valueFile path with a hole in it."""
    spec = _yaml(APPLICATIONSET)["spec"]
    assert spec["goTemplate"] is True
    assert "missingkey=error" in spec["goTemplateOptions"]


def test_app_of_apps_still_syncs_the_applicationset():
    """The ApplicationSet has to be applied by something. The app-of-apps
    syncs infra/gitops/argo/ with `exclude: app-of-apps.yaml`, so it picks up
    applicationset.yaml — but only while that exclusion stays narrow."""
    app_of_apps = _yaml(ARGO_DIR / "app-of-apps.yaml")
    source = app_of_apps["spec"]["source"]
    assert source["path"] == "infra/gitops/argo"
    assert source["directory"]["exclude"] == "app-of-apps.yaml", (
        "the app-of-apps exclusion changed; if it excludes applicationset.yaml "
        "nothing applies the ApplicationSet and every Application disappears"
    )


